def write_index(reg: dict[str, tuple[str, str]]) -> None:
    import json

    from common.provenance import RESULTS_DIR

    rows = ["# Results index", "", "Generated by `bench/make_report.py`. Every experiment: command, output file, "
            "evidence stage and a one-line finding. Stage is `sim`, `offline` or `real`. `_quick` files are "
            "smoke-scale reproductions (`make reproduce-quick`) and are never cited.", "",
            "| Stage | Output | Command | Commit | Finding |", "|---|---|---|---|---|"]
    for p in sorted(RESULTS_DIR.rglob("*.json")):
        try:
            d = json.loads(p.read_text())
        except json.JSONDecodeError:
            continue
        if not isinstance(d, dict) or "stage" not in d:
            continue
        name = str(p.relative_to(RESULTS_DIR))[:-5]
        finding, _ = render(FINDINGS.get(name, ""), reg)
        rows.append(f"| {d['stage']} | `results/{name}.json` | `{d.get('command') or ''}` | "
                    f"{d['git']['sha'][:8]}{'+dirty' if d['git']['dirty'] else ''} | {finding} |")
    (RESULTS_DIR / "INDEX.md").write_text("\n".join(rows) + "\n")


def main() -> None:
    write_index(registry())
    for target, text in build().items():
        p = REPO_ROOT / target
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        print("wrote", target)


if __name__ == "__main__":
    main()
