"""Render docs/templates/*.md -> repo docs, substituting {{key}} with values from bench/numbers.py.

Targets: README.md, RESUME_BULLETS.md, FINAL_REVIEW.md, paper/paper.md (template name = target path with '/'
replaced by '__'). Unknown keys are an error, so a doc can never cite a number the results do not contain.
"""

from __future__ import annotations

import re
from pathlib import Path

from bench.numbers import registry
from common.provenance import REPO_ROOT

TEMPLATES = REPO_ROOT / "docs" / "templates"
KEY = re.compile(r"\{\{\s*([A-Za-z0-9_.|()\-, ]+?)\s*\}\}")
HEADER = "<!-- GENERATED by bench/make_report.py from {src}; edit the template, not this file. -->\n"


def render(text: str, reg: dict[str, tuple[str, str]]) -> tuple[str, list[str]]:
    missing: list[str] = []

    def sub(m: re.Match) -> str:
        k = m.group(1)
        if k not in reg:
            missing.append(k)
            return f"<MISSING {k}>"
        return reg[k][0]

    return KEY.sub(sub, text), missing


def targets() -> list[tuple[Path, str]]:
    return [(p, p.name.replace("__", "/").removesuffix(".tmpl")) for p in sorted(TEMPLATES.glob("*.md.tmpl"))]


def build() -> dict[str, str]:
    reg = registry()
    out, problems = {}, []
    for tpl, target in targets():
        text, missing = render(tpl.read_text(), reg)
        problems += [f"{target}: unknown key {{{{{k}}}}}" for k in missing]
        out[target] = HEADER.format(src=f"docs/templates/{tpl.name}") + text
    if problems:
        raise SystemExit("\n".join(problems))
    return out


def main() -> None:
    for target, text in build().items():
        p = REPO_ROOT / target
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
        print("wrote", target)


if __name__ == "__main__":
    main()
